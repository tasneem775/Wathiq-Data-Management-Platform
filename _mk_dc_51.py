def register_tbl(doc):
    n = len(HV_REG)
    t = doc.add_table(rows=1+len(ASSETS), cols=n)
    t.style = "Table Grid"; _bd(t)
    hv_r = list(reversed(HV_REG))
    wv_r = list(reversed(WV_REG))
    # رأس الجدول
    for i, c in enumerate(t.rows[0].cells):
        _sh(c, HB); _ct(c, hv_r[i], bold=True, sz=8, wh=True, ctr=True)
    # صفوف البيانات
    for ri, a in enumerate(ASSETS):
        m, name, atype, dept, cls1, dg, per, cls2, dr = a
        rv = (m, name, atype, dept, cls1, dg, per, cls2, dr)
        rv_r = list(reversed(rv))
        bg = AL if ri % 2 == 0 else "FFFFFF"
        row = t.rows[ri+1]
        for i, c in enumerate(row.cells):
            val = rv_r[i]
            if i == 8:            # م — أقصى اليمين (cell[n-1])
                _sh(c, HB); _ct(c, val, bold=True, sz=8, wh=True, ctr=True)
            elif i == 4:          # تصنيف الممنوح
                fg, bk = CLASS_C.get(val, (HB, AL))
                _sh(c, bk); _ct(c, val, bold=True, sz=8, col=fg, ctr=True)
            elif i == 1:          # تصنيف المعتمد
                fg, bk = CLASS_C.get(val, (HB, AL))
                _sh(c, bk); _ct(c, val, bold=True, sz=8, col=fg, ctr=True)
            elif i == 6:          # نوع الأصل
                fg, bk = TYPE_C.get(val, (HB, AL))
                _sh(c, bk); _ct(c, val, sz=8, col=fg, ctr=True)
            else:
                _sh(c, bg); _ct(c, val, sz=8)
    _wid(t, wv_r)

