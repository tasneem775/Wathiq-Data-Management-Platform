# hv / wv في الترتيب البصري RTL (العمود الأيمن أولاً)
# المنطق: reversed(hv) و reversed(rv) و reversed(wv) تُطبَّق على الخلايا
# → cell[n-1] = أقصى اليمين = hv[0] = rv[0] = wv[0]
#
# ترتيب rv:  (م، اسم، نوع، إدارة، تصنيف_ممنوح، تاريخ_منح، فترة، تصنيف_معتمد، تاريخ_مراجعة)
# بعد العكس (rv_r): cell[0]=تاريخ_مراجعة، cell[1]=تصنيف_معتمد، cell[2]=فترة،
#                   cell[3]=تاريخ_منح، cell[4]=تصنيف_ممنوح، cell[5]=إدارة،
#                   cell[6]=نوع، cell[7]=اسم، cell[8]=م (أقصى اليمين)
