# ── helpers ───────────────────────────────────────────────────────────────────
def _rtl(p):
    b = OxmlElement("w:bidi"); b.set(qn("w:val"), "1")
    p._p.get_or_add_pPr().append(b)

def _af(r, bold=False, sz=11, col=None):
    r.bold = bold; r.font.name = "Times New Roman"
    pr = r._element.get_or_add_rPr()
    pr.get_or_add_rFonts().set(qn("w:cs"), "Times New Roman")
    r.font.size = Pt(sz)
    e = OxmlElement("w:rtl"); e.set(qn("w:val"), "1"); pr.append(e)
    if col: r.font.color.rgb = RGBColor.from_string(col)

def _sh(cell, f):
    s = OxmlElement("w:shd")
    s.set(qn("w:val"), "clear"); s.set(qn("w:color"), "auto"); s.set(qn("w:fill"), f)
    cell._tc.get_or_add_tcPr().append(s)

def _ct(cell, text, bold=False, sz=10, col=None, ctr=False, wh=False):
    p = cell.paragraphs[0]; p.clear(); _rtl(p)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if ctr else WD_ALIGN_PARAGRAPH.RIGHT
    c = col if col else ("FFFFFF" if wh else "000000")
    _af(p.add_run(text), bold, sz, c)

def _wid(t, ws):
    for row in t.rows:
        for i, cell in enumerate(row.cells):
            w = OxmlElement("w:tcW")
            w.set(qn("w:w"), str(ws[i])); w.set(qn("w:type"), "dxa")
            cell._tc.get_or_add_tcPr().append(w)

def _bd(t):
    tp = t._tbl.find(qn("w:tblPr"))
    if tp is None: tp = OxmlElement("w:tblPr"); t._tbl.insert(0, tp)
    bv = OxmlElement("w:bidiVisual"); bv.set(qn("w:val"), "1"); tp.append(bv)

def mk_tbl(hv, rv_list, wv, sz=9):
    """hv / rv_list: visual RTL (rightmost first). wv: same order."""
    n = len(hv); t = doc.add_table(rows=1 + len(rv_list), cols=n)
    t.style = "Table Grid"; _bd(t)
    for i, c in enumerate(t.rows[0].cells):
        _sh(c, HB)
        _ct(c, list(reversed(hv))[i], bold=True, sz=sz, wh=True, ctr=True)
    for ri, rv in enumerate(rv_list):
        row = t.rows[ri + 1]; bg = AL if ri % 2 == 0 else "FFFFFF"
        for i, c in enumerate(row.cells):
            _sh(c, bg); _ct(c, list(reversed(rv))[i], sz=sz)
    _wid(t, list(reversed(wv))); return t

def inv_tbl(rv_list):
    """
    Inventory table — 6 cols.
    hv visual RTL (rightmost first):
      م | اسم مجموعة البيانات أو السجل | نوع الأصل | الإدارة المالكة | مالك البيانات | حالة الجرد
    With bidiVisual:
      cells[0]=حالة  cells[1]=مالك  cells[2]=إدارة
      cells[3]=نوع   cells[4]=اسم   cells[5]=م
    """
    hv = ["م", "اسم مجموعة البيانات أو السجل", "نوع الأصل",
          "الإدارة المالكة", "مالك البيانات", "حالة الجرد"]
    wv = [380, 2050, 1080, 1750, 1750, 980]     # visual RTL widths  Σ=7990
    n = len(hv)
    t = doc.add_table(rows=1 + len(rv_list), cols=n)
    t.style = "Table Grid"; _bd(t)
    for i, c in enumerate(t.rows[0].cells):
        _sh(c, HB)
        _ct(c, list(reversed(hv))[i], bold=True, sz=9, wh=True, ctr=True)
    for ri, rv in enumerate(rv_list):
        # rv order: (م, اسم, نوع, إدارة, مالك, حالة)
        rv_xml = list(reversed(rv))  # XML (leftmost first): حالة,مالك,إدارة,نوع,اسم,م
        row = t.rows[ri + 1]
        status = rv_xml[0];  fg_s, bg_s = ST_COL.get(status, (HB, AL))
        naw    = rv_xml[3];  fg_t, bg_t = TY_COL.get(naw,    (HB, AL))
        for ci, c in enumerate(row.cells):
            val = rv_xml[ci]
            if ci == 0:              # حالة الجرد
                _sh(c, bg_s); _ct(c, val, bold=True, sz=9, col=fg_s, ctr=True)
            elif ci == 3:            # نوع الأصل
                _sh(c, bg_t); _ct(c, val, bold=False, sz=9, col=fg_t, ctr=True)
            elif ci == 5:            # م
                _sh(c, HB);  _ct(c, val, bold=True, sz=9, wh=True, ctr=True)
            else:
                _sh(c, AL if ri % 2 == 0 else "FFFFFF")
                _ct(c, val, sz=9)
    _wid(t, list(reversed(wv))); return t

