# ── impact assessment table A ─────────────────────────────────────────────────
def imp_tbl_a(rv_list):
    """
    8 cols visual RTL (rightmost first):
      م | اسم | نوع | إدارة | مصالح وطنية | جهات | أفراد | بيئة
    XML (leftmost first):
      بيئة[0] | أفراد[1] | جهات[2] | مصالح[3] | إدارة[4] | نوع[5] | اسم[6] | م[7]
    """
    hv = ["م","اسم الأصل","نوع الأصل","الإدارة المالكة",
          "المصالح الوطنية","الجهات","الأفراد","البيئة"]
    wv = [370, 2000, 870, 1550, 880, 740, 740, 700]   # Σ ≈ 7850
    n = len(hv)
    t = doc.add_table(rows=1+len(rv_list), cols=n); t.style="Table Grid"; _bd(t)
    for i,c in enumerate(t.rows[0].cells):
        _sh(c,HB); _ct(c, list(reversed(hv))[i], bold=True, sz=8, wh=True, ctr=True)
    # each rv: (م, اسم, نوع, إدارة, مصالح, جهات, أفراد, بيئة)
    for ri, rv in enumerate(rv_list):
        row = t.rows[ri+1]; rv_x = list(reversed(rv))
        for ci, c in enumerate(row.cells):
            val = rv_x[ci]
            if ci == 7:              # م  (rightmost visual)
                _sh(c, HB); _ct(c, val, bold=True, sz=8, wh=True, ctr=True)
            elif ci in (0,1,2,3):    # بيئة أفراد جهات مصالح  (impact columns)
                fg, bg = IMP_C.get(val, (HB, AL))
                _sh(c, bg); _ct(c, val, bold=True, sz=8, col=fg, ctr=True)
            elif ci == 5:            # نوع الأصل
                fg, bg = TYP_C.get(val, (HB, AL))
                _sh(c, bg); _ct(c, val, sz=8, col=fg, ctr=True)
            else:
                _sh(c, AL if ri%2==0 else "FFFFFF"); _ct(c, val, sz=8)
    _wid(t, list(reversed(wv))); return t

