def reg_matrix():
    """
    Regulatory conflict matrix — 7 cols visual RTL (rightmost first):
      م | اسم الأصل | الإدارة | نظام الجرائم المعلوماتية |
      نظام التجارة الإلكترونية | نظام حماية البيانات | التعارض الإجمالي
    XML leftmost first (reversed):
      إجمالي[0] | PDPL[1] | تجارة[2] | جرائم[3] | إدارة[4] | اسم[5] | م[6]
    """
    hv = ["م", "اسم الأصل البياني", "الإدارة المالكة",
          "نظام مكافحة الجرائم المعلوماتية",
          "نظام التجارة الإلكترونية",
          "نظام حماية البيانات الشخصية",
          "التعارض الإجمالي"]
    wv = [340, 1900, 1500, 1280, 1280, 1400, 1100]  # Σ = 8800
    n = len(hv)
    t = doc.add_table(rows=1 + len(ASSETS), cols=n)
    t.style = "Table Grid"; _bd(t)
    for i, c in enumerate(t.rows[0].cells):
        _sh(c, HB)
        _ct(c, list(reversed(hv))[i], bold=True, sz=8, wh=True, ctr=True)
    for ri, a in enumerate(ASSETS):
        # a: (م, اسم, نوع, إدارة, سبب, cyber, ecom, pdpl, overall, منافع, آثار, ميزان, قرار)
        m, name, _, dept, _, cyber, ecom, pdpl, overall = a[0], a[1], a[2], a[3], a[4], a[5], a[6], a[7], a[8]
        rv_x = list(reversed([m, name, dept, cyber, ecom, pdpl, overall]))
