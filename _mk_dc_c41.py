def kpi_card(doc, kpi):
    # عنوان البطاقة
    h2(doc, f"بطاقة المؤشر:  {kpi['رمز']}  —  {kpi['الاسم']}", col=HB)
    sp(doc)
    rows = []
    for label, key, key2 in CARD_FIELDS:
        if key2:
            val = f"{kpi[key]}  —  {kpi[key2]}"
        else:
            val = kpi[key]
        rows.append((label, val))
    n = len(rows)
    t = doc.add_table(rows=n, cols=2)
    t.style = "Table Grid"; _bd(t)
    wv_r = list(reversed([3300, 5700]))
    for ri, (lbl, val) in enumerate(rows):
        rv_r = list(reversed((lbl, val)))
        bg = AL if ri % 2 == 0 else "FFFFFF"
        status_row = (lbl == "حالة المؤشر")
        for i, c in enumerate(t.rows[ri].cells):
            v = rv_r[i]
            if i == 1:  # عمود التسمية (أقصى اليمين بعد العكس)
                _sh(c, "DDE6F1"); _ct(c, v, bold=True, sz=10, col=HB, ctr=True)
            elif status_row:
                fg, bk = STA_C.get(val, ("000000", AL))
                _sh(c, bk); _ct(c, v, bold=True, sz=10, col=fg, ctr=True)
            elif lbl == "قطبية المؤشر":
                fg, bk = POL_C.get(val.split(" |")[0].strip(), ("000000", AL))
                _sh(c, bk); _ct(c, v, sz=10, col=fg)
            else:
                _sh(c, bg); _ct(c, v, sz=10)
    _wid(t, wv_r)
    sp(doc)


