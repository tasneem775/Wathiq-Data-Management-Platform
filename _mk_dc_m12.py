# ── helpers ────────────────────────────────────────────────────────────────────
def _rtl(p):
    b = OxmlElement("w:bidi"); b.set(qn("w:val"), "1")
    p._p.get_or_add_pPr().append(b)

def _af(r, bold=False, sz=11, col=None):
    r.bold = bold; r.font.name = "Times New Roman"
    pr = r._element.get_or_add_rPr()
    pr.get_or_add_rFonts().set(qn("w:cs"), "Times New Roman")
    r.font.size = Pt(sz)
    e = OxmlElement("w:rtl"); e.set(qn("w:val"), "1"); pr.append(e)
    if col: r.font.color.rgb = RGBColor.from_string(col)

def _sh(cell, f):
    s = OxmlElement("w:shd")
    s.set(qn("w:val"), "clear"); s.set(qn("w:color"), "auto"); s.set(qn("w:fill"), f)
    cell._tc.get_or_add_tcPr().append(s)

def _ct(cell, text, bold=False, sz=10, col=None, ctr=False, wh=False):
    p = cell.paragraphs[0]; p.clear(); _rtl(p)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if ctr else WD_ALIGN_PARAGRAPH.RIGHT
    c = col if col else ("FFFFFF" if wh else "000000")
    _af(p.add_run(str(text)), bold, sz, c)

def _wid(t, ws):
    for row in t.rows:
        for i, cell in enumerate(row.cells):
            w = OxmlElement("w:tcW")
            w.set(qn("w:w"), str(ws[i])); w.set(qn("w:type"), "dxa")
            cell._tc.get_or_add_tcPr().append(w)

def _bd(t):
    tp = t._tbl.find(qn("w:tblPr"))
    if tp is None: tp = OxmlElement("w:tblPr"); t._tbl.insert(0, tp)
    bv = OxmlElement("w:bidiVisual"); bv.set(qn("w:val"), "1"); tp.append(bv)

def mk_tbl(doc, hv, rv_list, wv, sz=9):
    n = len(hv)
    t = doc.add_table(rows=1 + len(rv_list), cols=n)
    t.style = "Table Grid"; _bd(t)
    hv_r = list(reversed(hv)); wv_r = list(reversed(wv))
    for i, c in enumerate(t.rows[0].cells):
        _sh(c, HB); _ct(c, hv_r[i], bold=True, sz=sz, wh=True, ctr=True)
    for ri, rv in enumerate(rv_list):
        row = t.rows[ri + 1]; bg = AL if ri % 2 == 0 else "FFFFFF"
        rv_r = list(reversed(rv))
        for i, c in enumerate(row.cells):
            _sh(c, bg); _ct(c, rv_r[i], sz=sz)
    _wid(t, wv_r)

def mk_tbl_colored(doc, hv, rv_list, wv, col_configs, sz=9):
    n = len(hv)
    t = doc.add_table(rows=1 + len(rv_list), cols=n)
    t.style = "Table Grid"; _bd(t)
    hv_r = list(reversed(hv)); wv_r = list(reversed(wv))
    phys = {(n - 1 - ci): (cm, bd) for ci, cm, bd in col_configs}
    for i, c in enumerate(t.rows[0].cells):
        _sh(c, HB); _ct(c, hv_r[i], bold=True, sz=sz, wh=True, ctr=True)
    for ri, rv in enumerate(rv_list):
        row = t.rows[ri + 1]; bg = AL if ri % 2 == 0 else "FFFFFF"
        rv_r = list(reversed(rv))
        for i, c in enumerate(row.cells):
            val = rv_r[i]
            if i in phys:
                cm, bd = phys[i]
                fg, bk = cm.get(val, ("000000", bg))
                _sh(c, bk); _ct(c, val, bold=bd, sz=sz, col=fg, ctr=True)
            else:
                _sh(c, bg); _ct(c, val, sz=sz)
    _wid(t, wv_r)

def kpi_card(doc, rows, sz=10):
    """بطاقة مؤشر أداء — جدول ثنائي العمود (الحقل | القيمة)."""
    t = doc.add_table(rows=1 + len(rows), cols=2)
    t.style = "Table Grid"; _bd(t)
    # Header — reversed: physical[0]=القيمة, physical[1]=الحقل
    for i, txt in enumerate(["القيمة", "الحقل"]):
        _sh(t.rows[0].cells[i], HB)
        _ct(t.rows[0].cells[i], txt, bold=True, sz=sz, wh=True, ctr=True)
    for ri, (field, val) in enumerate(rows):
        row = t.rows[ri + 1]
        bg = AL if ri % 2 == 0 else "FFFFFF"
        # physical[1] = الحقل (rightmost visual in RTL)
        _sh(row.cells[1], HB if ri == 0 else bg)
        _ct(row.cells[1], field, bold=True, sz=sz,
            col="FFFFFF" if ri == 0 else "000000")
        # physical[0] = القيمة (leftmost visual in RTL)
        if val in STATUS_C:
            fg, bk = STATUS_C[val]
            _sh(row.cells[0], bk)
            _ct(row.cells[0], val, bold=True, sz=sz, col=fg, ctr=True)
        else:
            _sh(row.cells[0], bg)
            _ct(row.cells[0], val, sz=sz)
    _wid(t, [5500, 3500])

def h1(doc, tx):
    p = doc.add_paragraph(); _rtl(p); p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    pr = p._p.get_or_add_pPr()
    bd = OxmlElement("w:pBdr"); bo = OxmlElement("w:bottom")
    for k, v in [("w:val","single"),("w:sz","12"),("w:space","1"),("w:color",SB)]:
        bo.set(qn(k), v)
    bd.append(bo); pr.append(bd)
    _af(p.add_run(tx), bold=True, sz=14, col=HB)

def h2(doc, tx, col=None):
    p = doc.add_paragraph(); _rtl(p); p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    _af(p.add_run(tx), bold=True, sz=12, col=col or SB)

def pa(doc, tx, sz=11):
    p = doc.add_paragraph(); _rtl(p); p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    _af(p.add_run(tx), sz=sz)

def bu(doc, tx, sz=11):
    p = doc.add_paragraph(); _rtl(p); p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    _af(p.add_run("•  " + tx), sz=sz)

def sp(doc): doc.add_paragraph()

