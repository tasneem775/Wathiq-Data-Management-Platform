# ── catalog table helper ──────────────────────────────────────────────────────
def catalog_tbl():
    """
    8 cols visual RTL (rightmost first):
      م | اسم | إدارة | نوع | تصنيف | تاريخ | حالة | معرف الأصل
    XML (leftmost first, reversed):
      معرف[0] | حالة[1] | تاريخ[2] | تصنيف[3] | نوع[4] | إدارة[5] | اسم[6] | م[7]
    """
    hv = ["م", "اسم مجموعة البيانات / السجل", "الإدارة المالكة",
          "نوع الأصل", "مستوى التصنيف", "تاريخ الإدراج",
          "حالة التحديث", "معرف الأصل"]
    wv = [340, 1900, 1500, 850, 900, 800, 870, 1040]  # Σ = 8200
    n = len(hv)
    t = doc.add_table(rows=1 + len(DATA), cols=n)
    t.style = "Table Grid"; _bd(t)
    for i, c in enumerate(t.rows[0].cells):
        _sh(c, HB)
        _ct(c, list(reversed(hv))[i], bold=True, sz=8, wh=True, ctr=True)
    for ri, row_d in enumerate(DATA):
        m, name, dept, typ, cls, dt, sta, rid = row_d
        rv_x = list(reversed([m, name, dept, typ, cls, dt, sta, rid]))
        # XML: معرف[0],حالة[1],تاريخ[2],تصنيف[3],نوع[4],إدارة[5],اسم[6],م[7]
        row = t.rows[ri + 1]
        for ci, c in enumerate(row.cells):
            val = rv_x[ci]
            if ci == 3:    # تصنيف
                fg, bg = CLS_C.get(val, (HB, AL))
                _sh(c, bg); _ct(c, val, bold=True, sz=8, col=fg, ctr=True)
            elif ci == 4:  # نوع
                fg, bg = TYP_C.get(val, (HB, AL))
                _sh(c, bg); _ct(c, val, sz=8, col=fg, ctr=True)
            elif ci == 1:  # حالة
                fg, bg = STA_C.get(val, (HB, AL))
                _sh(c, bg); _ct(c, val, bold=True, sz=8, col=fg, ctr=True)
            elif ci == 7:  # م
                _sh(c, HB); _ct(c, val, bold=True, sz=8, wh=True, ctr=True)
            elif ci == 0:  # معرف (monospace-ish)
                _sh(c, AL if ri % 2 == 0 else "FFFFFF")
                _ct(c, val, sz=8, ctr=True)
            else:
                _sh(c, AL if ri % 2 == 0 else "FFFFFF"); _ct(c, val, sz=8)
    _wid(t, list(reversed(wv))); return t

