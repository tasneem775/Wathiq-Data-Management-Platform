# ── helpers ────────────────────────────────────────────────────────────────────
def _rtl(p):
    pPr = p._p.get_or_add_pPr()
    b = OxmlElement("w:bidi"); b.set(qn("w:val"),"1"); pPr.append(b)

def _af(r, bold=False, sz=11, col=None):
    r.font.name = "Times New Roman"
    r._r.get_or_add_rPr().append(OxmlElement("w:rtl"))
    e = OxmlElement("w:rFonts")
    e.set(qn("w:cs"),"Times New Roman"); r._r.get_or_add_rPr().insert(0,e)
    r.font.size = Pt(sz); r.font.bold = bold
    if col: r.font.color.rgb = RGBColor.from_string(col)

def _sh(cell, f):
    tc = cell._tc; tcPr = tc.get_or_add_tcPr()
    s = OxmlElement("w:shd")
    s.set(qn("w:val"),"clear"); s.set(qn("w:color"),"auto"); s.set(qn("w:fill"),f)
    tcPr.append(s)

def _ct(cell, text, bold=False, sz=10, col=None, ctr=False, wh=False):
    cell.text = ""
    p = cell.paragraphs[0]
    _rtl(p)
    if ctr: p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(str(text))
    _af(r, bold=bold, sz=sz, col=col if not wh else "FFFFFF")

def _wid(t, ws):
    tbl = t._tbl
    for i, tr in enumerate(tbl.tr_lst):
        for j, tc in enumerate(tr.tc_lst):
            tcPr = tc.get_or_add_tcPr()
            for old in tcPr.findall(qn("w:tcW")): tcPr.remove(old)
            w = OxmlElement("w:tcW")
            w.set(qn("w:w"), str(ws[j])); w.set(qn("w:type"),"dxa")
            tcPr.append(w)

def _bd(t):
    tbl = t._tbl
    tblPr = tbl.find(qn("w:tblPr"))
    if tblPr is None:
        tblPr = OxmlElement("w:tblPr")
        tbl.insert(0, tblPr)
    bv = OxmlElement("w:bidiVisual"); bv.set(qn("w:val"),"1"); tblPr.append(bv)

def mk_tbl(doc, hv, rv_list, wv, sz=9):
    t = doc.add_table(rows=1+len(rv_list), cols=len(hv))
    t.style = "Table Grid"
    _bd(t)
    hr = t.rows[0]
    for j, h in enumerate(hv):
        c = hr.cells[j]
        _sh(c,"1F3864")
        _ct(c,h,bold=True,sz=sz,wh=True,ctr=True)
    for i, rv in enumerate(rv_list):
        row = t.rows[i+1]
        rvr = list(reversed(rv))
        bg = "F2F2F2" if i%2==0 else "FFFFFF"
        for j, val in enumerate(rvr):
            c = row.cells[j]
            _sh(c, bg)
            _ct(c, val, sz=sz, ctr=True)
    _wid(t, wv)
    return t

